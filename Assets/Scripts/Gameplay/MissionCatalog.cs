    public class MissionDefinition
    {
        public string Title;
        public string Summary;
        public string Briefing;
        public string VictoryText;
        public int AlbumsRequired;
        public int ExtraAsteroids;
        public float SpawnInterval;
        public float AsteroidSpeed;
        public int Damage;
        public float LargeChance;
        public float MissileInterval;
        public float MissileSpeed;
        public int MissileBurst;
        public bool HasBoss;
        public int SectorIndex;
        public string UnlockedMechanic;

        public MissionDefinition(
            string title,
            string summary,
            string briefing,
            string victoryText,
            int albumsRequired,
            int extraAsteroids,
            float spawnInterval,
            float asteroidSpeed,
            int damage,
            float largeChance,
            float missileInterval,
            float missileSpeed,
            int missileBurst,
            bool hasBoss,
            int sectorIndex,
            string unlockedMechanic = null)
        {
            Title = title;
            Summary = summary;
            Briefing = briefing;
            VictoryText = victoryText;
            AlbumsRequired = albumsRequired;
            ExtraAsteroids = extraAsteroids;
            SpawnInterval = spawnInterval;
            AsteroidSpeed = asteroidSpeed;
            Damage = damage;
            LargeChance = largeChance;
            MissileInterval = missileInterval;
            MissileSpeed = missileSpeed;
            MissileBurst = missileBurst;
            HasBoss = hasBoss;
            SectorIndex = sectorIndex;
            UnlockedMechanic = unlockedMechanic;
        }
    }

