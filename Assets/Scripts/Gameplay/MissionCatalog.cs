    public static class PilotRank
    {
        public static string Title(int kills)
        {
            if (kills >= 150)
                return "Ас Гравитации";
            if (kills >= 80)
                return "Ветеран Hypeverse";
            if (kills >= 40)
                return "Штурман Зигги";
            if (kills >= 15)
                return "Кадет Тарелки";
            if (kills >= 5)
                return "Новичок";
            return "Пилот";
        }
    }
