    public class LoreEntry
    {
        public string Id;
        public string Title;
        public string Category;
        public string Content;

        public LoreEntry(string id, string title, string category, string content)
        {
            Id = id;
            Title = title;
            Category = category;
            Content = content;
        }
    }

    public class MissionDialogue
    {
        public string Speaker;
        public string Header;
        public string[] IntroLines;
        public string BossWarning;
        public string TutorialIntro;

        public MissionDialogue(string speaker, string header, string[] introLines, string bossWarning, string tutorialIntro = null)
        {
            Speaker = speaker;
            Header = header;
            IntroLines = introLines;
            BossWarning = bossWarning;
            TutorialIntro = tutorialIntro;
        }
    }

